        await page.locator('textarea').fill('Browser receipt');
        await page.getByRole('button', { name: 'Lưu', exact: true }).click();
        await page.getByRole('heading', { name: 'Nhập hàng vào chi nhánh', exact: true }).waitFor({ state: 'hidden' });
