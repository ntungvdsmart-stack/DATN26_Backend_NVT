        assert.equal(branchOptions, 1);
        await page.getByText('Fixture shirt', { exact: true }).first().click();
        const [[beforeReceipt]] = await fixture.db.query('SELECT SUM(quantity) AS total FROM inventory WHERE branch_id=1');
